#!/usr/bin/env node
/**
 * Writes docs/tools.md from the server itself.
 *
 * The tool list, descriptions, and arguments all come from the running server,
 * so the reference cannot drift away from the code. Run `npm run docs:tools`
 * after adding or changing a tool.
 */
import { writeFileSync } from 'node:fs';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { InMemoryTransport } from '@modelcontextprotocol/sdk/inMemory.js';
import pino from 'pino';
import { configSchema } from '../dist/config/schema.js';
import { buildServer } from '../dist/server.js';
import { TOOL_GROUPS } from '../dist/tools/registry.js';

const config = configSchema.parse({
    zosmf: { host: 'docs.example', user: 'DOCS', password: 'docs' },
    mcp: {},
    limits: {},
    enterprise: {},
    security: {},
});

const server = buildServer(config, pino({ level: 'silent' }));
const client = new Client({ name: 'docs', version: '1.0.0' });
const [clientTransport, serverTransport] = InMemoryTransport.createLinkedPair();
await server.connect(serverTransport);
await client.connect(clientTransport);

const { tools } = await client.listTools();
const byName = new Map(tools.map((tool) => [tool.name, tool]));

/** Render one tool's arguments as a table, or a note when it takes none. */
function renderArguments(schema) {
    const properties = Object.entries(schema?.properties ?? {});
    if (properties.length === 0) return '_No arguments._\n';

    const required = new Set(schema.required ?? []);
    const rows = properties.map(([name, spec]) => {
        const type = spec.enum ? spec.enum.map((v) => `\`${v}\``).join(' \\| ') : spec.type;
        return `| \`${name}\` | ${type} | ${required.has(name) ? 'yes' : 'no'} | ${spec.description ?? ''} |`;
    });
    return [
        '| Argument | Type | Required | Description |',
        '| --- | --- | --- | --- |',
        ...rows,
    ].join('\n');
}

const lines = [
    '<!-- Generated by scripts/generate-tool-docs.mjs. Do not edit by hand. -->',
    '',
    '# Tool reference',
    '',
    `All ${tools.length} tools, grouped the same way as the code in \`src/tools/\`.`,
    '',
    '## Contents',
    '',
    ...TOOL_GROUPS.map(
        (group) => `- [${group.title}](#${group.title.toLowerCase().replace(/[^a-z0-9]+/g, '-')})`,
    ),
    '',
];

for (const group of TOOL_GROUPS) {
    lines.push(`## ${group.title}`, '', group.summary, '');
    if (group.requires) {
        lines.push(`> **Needs configuration:** ${group.requires.join(', ')}`, '');
    }
    for (const tool of group.tools) {
        const advertised = byName.get(tool.name);
        lines.push(
            `### \`${tool.name}\``,
            '',
            advertised.description,
            '',
            renderArguments(advertised.inputSchema),
            '',
        );
    }
}

writeFileSync(
    'docs/tools.md',
    lines
        .join('\n')
        .replace(/\n{3,}/g, '\n\n')
        .trimEnd() + '\n',
);
console.log(`docs/tools.md written — ${tools.length} tools`);

await client.close();
await server.close();
